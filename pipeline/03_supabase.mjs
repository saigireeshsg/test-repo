// Step 3 - Load the index into Supabase (Postgres + pgvector).
//
//   node pipeline/03_supabase.mjs --sql      writes supabase/seed.sql (used by `supabase db reset`, or paste into the SQL editor)
//   node pipeline/03_supabase.mjs --upload   upserts rows over the REST API
//        needs SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY in the environment (service role: writes bypass RLS)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const D = join(ROOT, 'web', 'data');
const ix = JSON.parse(readFileSync(join(D, 'gita_index.json'), 'utf8'));
const f32 = (f) => { const b = readFileSync(join(D, f)); return new Float32Array(b.buffer, b.byteOffset, b.byteLength / 4); };
const VE = f32('verse_embeddings.f32'), SE = f32('section_embeddings.f32'), TE = f32('theme_embeddings.f32');
const DIM = ix.dim;
const vec = (M, i) => '[' + Array.from(M.subarray(i * DIM, (i + 1) * DIM), (x) => x.toFixed(6)).join(',') + ']';

const rows = {
  gita_themes: ix.themes.map((t, i) => ({ id: t.id, name: t.name, description: t.description, embedding: vec(TE, i) })),
  gita_chapters: ix.chapters.map((c) => ({
    chapter: c.chapter, name_sanskrit: c.name_sanskrit, name_english: c.name_english,
    hexad: c.hexad, summary: c.summary, verse_count: c.verse_count,
  })),
  gita_sections: ix.sections.map((s, i) => ({
    id: s.id, chapter: s.chapter, start_verse: s.start, end_verse: s.end, label: s.label, title: s.title,
    themes: s.themes, content: s.text, embedding: vec(SE, i), pca: s.pca, umap: s.umap,
  })),
  gita_verses: ix.verses.map((v, i) => ({
    id: v.id, chapter: v.chapter, verse: v.verse, section_id: v.section_id, speaker: v.speaker, hexad: v.hexad,
    primary_theme: v.primary_theme, themes: v.themes, theme_scores: v.theme_scores,
    sanskrit_iast: v.sanskrit_iast, sanskrit_devanagari: v.sanskrit_devanagari, english: v.english,
    alignment: v.alignment, embedding: vec(VE, i), pca: v.pca, umap: v.umap,
  })),
};

const lit = (x) => {
  if (x === null || x === undefined) return 'null';
  if (typeof x === 'number') return String(x);
  if (Array.isArray(x)) return x.length && typeof x[0] === 'number'
    ? `'{${x.join(',')}}'`
    : `array[${x.map(lit).join(',')}]::text[]`;
  if (typeof x === 'object') return `'${JSON.stringify(x).replace(/'/g, "''")}'::jsonb`;
  return `'${String(x).replace(/'/g, "''")}'`;
};

if (process.argv.includes('--sql')) {
  const out = ['-- generated by pipeline/03_supabase.mjs - do not edit', 'begin;',
    'truncate public.gita_verses, public.gita_sections, public.gita_chapters, public.gita_themes cascade;'];
  for (const [table, rs] of Object.entries(rows)) {
    const cols = Object.keys(rs[0]);
    for (const r of rs) out.push(`insert into public.${table} (${cols.join(',')}) values (${cols.map((c) => lit(r[c])).join(',')});`);
  }
  out.push('commit;');
  writeFileSync(join(ROOT, 'supabase', 'seed.sql'), out.join('\n') + '\n');
  console.log('wrote supabase/seed.sql', Object.fromEntries(Object.entries(rows).map(([k, v]) => [k, v.length])));
} else if (process.argv.includes('--upload')) {
  const url = process.env.SUPABASE_URL, key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !key) throw new Error('set SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY');
  for (const [table, rs] of Object.entries(rows)) {
    for (let i = 0; i < rs.length; i += 100) {
      const res = await fetch(`${url}/rest/v1/${table}`, {
        method: 'POST',
        headers: { apikey: key, Authorization: `Bearer ${key}`, 'Content-Type': 'application/json', Prefer: 'resolution=merge-duplicates,return=minimal' },
        body: JSON.stringify(rs.slice(i, i + 100)),
      });
      if (!res.ok) throw new Error(`${table}: ${res.status} ${await res.text()}`);
    }
    console.log(`upserted ${rs.length} rows into ${table}`);
  }
} else {
  console.log('usage: node pipeline/03_supabase.mjs --sql | --upload');
}
